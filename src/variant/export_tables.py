#!/usr/bin/env python3
"""Export a validation variant's candidate-set data for the C++ search
(src/variant/cpp): the exact |C_V| from count.candidates.count and the per-file
feature tables that is_candidate uses (file_features at level "file"), so that
the C++ candidate test is the same function on the same data.

Usage: python3 src/variant/export_tables.py V1 > src/variant/cpp/tables/V1.txt
Format (whitespace separated, '#' comments):
  variant NAME NF NR ZONE COLOUR(0/1)
  total |C_V|
  etypes N  (COLOUR KIND)*          promotable confined slot types, sorted
  group COLOUR KIND MAX PROMOTABLE MINIMUM  [class list for Bound]   free-piece groups
  file X NSLOTS  (NAME COLOUR KIND START)*
  cfg X  u_1 .. u_NSLOTS  cb cw j  elig_1 .. elig_N      one line per admissible config
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from count.candidates import Bound, Std, count, elig_types, file_features, _admissible   # noqa: E402
from variant.bfs import variants                                                        # noqa: E402


def export(name, out=sys.stdout):
    var, setup, colour = variants()[name]
    etypes = elig_types(setup)
    total = count(setup, "file", colour).total
    w = out.write
    w(f"# candidate tables of validation variant {name}, generated by src/variant/export_tables.py\n")
    w(f"variant {name} {setup.nfiles} {setup.nranks} {setup.zone} {int(colour)}\n")
    w(f"total {total}\n")
    w(f"etypes {len(etypes)}" + "".join(f" {c} {k}" for c, k in etypes) + "\n")
    for c in "BW":
        for g in setup.free[c]:
            if isinstance(g, Std):
                w(f"group {c} {g.name} {g.n} {int(g.promotable)} {g.minimum}\n")
            elif isinstance(g, Bound):
                w(f"group {c} {g.name} {len(g.start_classes)} 1 0 bound" +
                  "".join(f" {cls}" for cls in g.start_classes) + "\n")
            else:
                raise ValueError(f"group type not supported: {g}")
    for x, slots in enumerate(setup.files):
        w(f"file {x} {len(slots)}" + "".join(f" {s.name} {s.colour} {s.kind} {s.start}" for s in slots) + "\n")
        for u in sorted(_admissible(tuple(slots), setup.nranks, setup.zone)):
            f = file_features(setup, x, u, "file", colour)
            assert f is not None
            _, _, cb, cw, j, _, _, elig = f
            w(f"cfg {x}" + "".join(f" {r}" for r in u) + f" {cb} {cw} {j}" +
              "".join(f" {elig.get(t, 0)}" for t in etypes) + "\n")


if __name__ == "__main__":
    export(sys.argv[1])
