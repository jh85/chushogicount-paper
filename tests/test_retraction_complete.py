"""Completeness of jcsa.mate_ending.predecessors against the engine's forward moves:
for random candidate positions P with White to move (colour-swapped samples), every
legal White move m (engine) must be reproduced by the retraction of T = P + m, i.e.
(P, m) must appear among predecessors(T) (before the candidate / engine filters).
Usage: python3 tests/test_retraction_complete.py [--positions 30 --procs 14 --seed 3]"""
import argparse
import random
import sys
from multiprocessing import Pool
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

_ctx = {}


def _init():
    from count.candidates import PRIMARY, chu_setup
    from count.sampler import Sampler
    from plan.engine import Engine
    _ctx["S"] = Sampler(chu_setup("file", **PRIMARY), "file", True)
    _ctx["E"] = Engine()
    # The current predecessor pre-filter needs the canonical free-piece groups.
    from jcsa.mate_ending import _init as init_predecessors
    init_predecessors(sampler=False)


def swap(board):
    """180° rotation + colour swap: a Black-to-move candidate becomes a White-to-move one."""
    return {(11 - x, 13 - y): ("W" if c == "B" else "B", r) for (x, y), (c, r) in board.items()}


def _work(seed):
    from count.sampler import to_sfen
    from count.sfen import parse
    from jcsa.mate_ending import predecessors
    from plan.moves import usi_squares
    rng = random.Random(seed)
    E = _ctx["E"]
    while True:
        b = _ctx["S"].sample(rng)[0]
        if any(p == ("B", "K") for p in b.values()):
            break
    P = swap(b)                                   # White to move, White has a royal
    sfen = to_sfen(P, "w")
    E.position(sfen)
    moves = sorted(E.legal())
    missed = []
    for mv in moves:
        E.position(sfen, [mv])
        T = parse(E.sfen())[0]
        if not any(p == ("B", "K") for p in T.values()):
            continue                              # terminal for Black: outside the study
        sqs = usi_squares(mv)
        if sqs[0] == sqs[-1] and len(sqs) == 2:
            continue                              # jitto: same board, not generated by design
        found = False
        for Q, m2 in predecessors(T):
            if m2 == mv and Q == P:
                found = True
                break
        if not found:
            missed.append(mv)
    return sfen, len(moves), missed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--positions", type=int, default=30)
    ap.add_argument("--procs", type=int, default=14)
    ap.add_argument("--seed", type=int, default=3)
    a = ap.parse_args()
    tot = bad = 0
    with Pool(a.procs, initializer=_init) as pool:
        for sfen, n, missed in pool.imap_unordered(_work, [a.seed * 1000 + i for i in range(a.positions)]):
            tot += n
            if missed:
                bad += len(missed)
                print(f"MISSED {len(missed)} of {n}: {missed[:5]}  {sfen}", flush=True)
    print(f"{a.positions} positions, {tot} legal White moves checked, {bad} not reproduced by the retraction")
    assert bad == 0


if __name__ == "__main__":
    main()
